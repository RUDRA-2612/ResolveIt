-- App Users Table (linked to Supabase auth.users)
CREATE TABLE public.app_user (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  name TEXT,
  avatar_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Roles Table
CREATE TABLE public.role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT UNIQUE NOT NULL
);

-- User Role Mapping
CREATE TABLE public.user_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.app_user(id) ON DELETE CASCADE,
  role_id BIGINT REFERENCES public.role(id) ON DELETE CASCADE,
  UNIQUE(user_id, role_id)
);

-- Departments Table
CREATE TABLE public.department (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT UNIQUE NOT NULL,
  code TEXT
);

-- Categories Table
CREATE TABLE public.category (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id BIGINT REFERENCES public.department(id) ON DELETE CASCADE,
  name TEXT NOT NULL
);

-- Main Grievance Tickets Table
CREATE TABLE public.ticket (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES public.app_user(id) ON DELETE CASCADE,
  department_id BIGINT REFERENCES public.department(id) ON DELETE SET NULL,
  category_id BIGINT REFERENCES public.category(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  specific_issue TEXT,
  description TEXT,
  building TEXT,
  exact_location TEXT,
  image_url TEXT,
  status TEXT DEFAULT 'Not Started',
  status_color TEXT DEFAULT 'rose',
  current_level INT DEFAULT 1,
  assigned_authority TEXT,
  is_escalated BOOLEAN DEFAULT FALSE,
  escalated_from TEXT,
  escalation_reason TEXT,
  is_confidential BOOLEAN DEFAULT FALSE,
  sla_due_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ticket Upvotes Table
CREATE TABLE public.upvote (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT REFERENCES public.ticket(id) ON DELETE CASCADE,
  user_id UUID REFERENCES public.app_user(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(ticket_id, user_id)
);

-- Ticket Updates & Official Comments
CREATE TABLE public.ticket_update (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT REFERENCES public.ticket(id) ON DELETE CASCADE,
  user_id UUID REFERENCES public.app_user(id) ON DELETE CASCADE,
  author_name TEXT NOT NULL,
  content TEXT NOT NULL,
  update_type TEXT DEFAULT 'official_update',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

