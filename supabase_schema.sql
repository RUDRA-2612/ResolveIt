-- ============================================================================
-- 5. AUTOMATED POSTGRES TRIGGER FOR AUTH REGISTRATIONS
-- Bypasses frontend sync calls and directly seeds new auth users to app_user
-- ============================================================================

CREATE OR REPLACE FUNCTION public.handle_new_user_signup()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  student_role_id BIGINT;
BEGIN
  -- Insert into public.app_user
  INSERT INTO public.app_user (id, email, name)
  VALUES (
    NEW.id, 
    NEW.email, 
    COALESCE(NEW.raw_user_meta_data->>'full_name', SPLIT_PART(NEW.email, '@', 1))
  )
  ON CONFLICT (id) DO NOTHING;

  -- Default assignment to 'student' role
  SELECT id INTO student_role_id FROM public.role WHERE name = 'student' LIMIT 1;

  IF student_role_id IS NOT NULL THEN
    INSERT INTO public.user_role (user_id, role_id)
    VALUES (NEW.id, student_role_id)
    ON CONFLICT DO NOTHING;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user_signup();